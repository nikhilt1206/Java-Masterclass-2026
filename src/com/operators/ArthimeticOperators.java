package com.operators;

public class ArthimeticOperators {

	public static void main(String[] args) {
	
		// Mathematical Operators : +,-,*,/,%,
		int number1 = 10;
		int number2 = 20;
		double result;
		result = number1 + number2;
		System.out.println(result);
		result = number1 - number2;
		System.out.println(result);
		result = number1*number2;
		System.out.println(result);
		result = ((double)number1)/number2;
		System.out.println(result);
		result = number1 % number2;
		System.out.println(result);    
		
	}
}
